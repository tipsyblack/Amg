import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";

// Чек-лист, по которому сценарий проверяется на маркетинг.
//
// Лежит отдельным ТЕКСТОВЫМ файлом, а не в коде, и это принципиально. Правила
// вкуса меняются вместе с продуктом, аудиторией и площадкой; если каждая
// правка требует программиста и деплоя, контент-завод встаёт. Здесь же
// редактор правит текст — в файле на сервере или прямо из чата командой
// /rules — и следующий сценарий проверяется уже по новому.
//
// Что осталось в коде и почему. В коде проверяется только СТРУКТУРА: ритм,
// бюджет слов, длина хука, реклама не в финале. Это объективные вещи, они не
// зависят от темы и не устаревают. Всё, что про смысл и вкус, ушло сюда:
// регулярка на «непростую задачу» ловит одну формулировку из тысячи, а модель
// понимает, что финал пустой, как бы он ни был сформулирован.

export const CHECKLIST_FILE = path.resolve("data/review-checklist.md");

export const DEFAULT_CHECKLIST = `# Чек-лист проверки сценария

Правь этот файл под свой продукт и аудиторию — он не в коде, деплой не нужен.
Каждый пункт — то, за что сценарий возвращают на переписывание.

## 1. Тема ведёт к продукту

Боль, описанная в хуке, должна быть болью того же человека, которому потом
пригодится продукт. Проверка: если закрыть последнюю сцену, догадается ли
зритель, что ему сейчас предложат?

Плохо: ролик про энергопотребление дата-центров, а в финале — «попробуй наш
бот для картинок». Зритель не собирался обучать нейросеть, эта боль не его, и
финал читается как «а теперь реклама».

## 2. Хук цепляет в первые три секунды

Первая сцена должна давать конкретику, за которую цепляется внимание: цифру,
парадокс, узнаваемую ситуацию, вопрос с неочевидным ответом. Утверждение об
отрасли («это стало настоящей проблемой») хуком не является: чья проблема,
почему моя?

Если в ролике есть яркая цифра — она должна звучать в хуке, а не в середине.

## 3. Ролик идёт вперёд, а не пересказывает сам себя

Каждая сцена должна добавлять то, чего зритель ещё не слышал. Мысль из первой
половины не должна возвращаться во второй — ни теми же словами, ни другими.

Проверка: выпиши смысл каждой сцены одной фразой. Если две строчки можно
поменять местами или вычеркнуть одну без потери — это повтор.

Плохо: «искать дизайнера долго и дорого» на девятой секунде и «зачем платить
и ждать, если можно сделать самому быстро» на сороковой. Слова разные, мысль
одна, и зритель чувствует, что ролик встал. Так же «пейзаж, портрет, мультик —
что угодно» и следом «это не только картинки: видео, текст, музыка» — второе
перечисление поглощает первое.

Отдельно смотри на связки: между соседними сценами должно читаться «поэтому»,
«но», «а значит». Если сцены можно перетасовать и ничего не изменится — это
список пунктов, а не история.

## 4. Финал содержательной части даёт вывод

Предпоследняя сцена (перед призывом) должна оставлять зрителю что-то: вывод,
который можно применить, мнение, с которым можно спорить, факт, которым
хочется поделиться. «Учёные работают над этим», «время покажет» — это
разведённые руки: уносить нечего, пересылать незачем.

## 5. Призыв конкретный и короткий

Одно предложение: что человек получит и почему это ему ничего не стоит.
«Там много интересного» и «заходи, не пожалеешь» — вежливость, а не
предложение. Не длиннее двадцати слов.

## 6. Один тон на весь ролик

Либо по-свойски везде, либо ровно везде. Одно сленговое слово посреди
энциклопедического текста звучит как чужая заплатка.

## 7. Примеры свежие

Модель или продукт из позапрошлого поколения датирует ролик целиком.
Исключение — намеренная историческая рамка («тогда это было чудом»).

## 8. Текст читается вслух

Синтезатор произносит реплики слово в слово. Сломанные согласования и падежи
будут произнесены именно так и звучат как брак.
`;

/** Текущий чек-лист: из файла, если он есть, иначе встроенный по умолчанию. */
export function readChecklist(): string {
  try {
    if (existsSync(CHECKLIST_FILE)) {
      const text = readFileSync(CHECKLIST_FILE, "utf-8").trim();
      if (text) return text;
    }
  } catch {
    // Нечитаемый файл — не повод ронять генерацию: работаем по умолчанию.
  }
  return DEFAULT_CHECKLIST;
}

export function writeChecklist(text: string): void {
  mkdirSync(path.dirname(CHECKLIST_FILE), { recursive: true });
  writeFileSync(CHECKLIST_FILE, `${text.trim()}\n`, "utf-8");
}

/** Вернуть чек-лист к встроенному варианту. */
export function resetChecklist(): void {
  writeChecklist(DEFAULT_CHECKLIST);
}
