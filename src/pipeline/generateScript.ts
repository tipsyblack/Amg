import { config } from "./config";

interface ScriptScene {
  caption: string;
  voiceoverText: string;
  // Объект, который появляется поверх картинки сцены, не заменяя её.
  // Необязательно: нет объекта — сцена как раньше.
  overlay?: {
    // Что нарисовать: один предмет, коротко.
    object: string;
    // На каком слове реплики он должен появиться.
    word?: string;
    // Объект остаётся в кадре и после смены картинки — связывает две сцены.
    acrossCut?: boolean;
  };
}

export interface GeneratedScript {
  title: string;
  scenes: ScriptScene[];
}

// Хук — короткая новость плюс, при желании, фраза-зацепка («сейчас расскажу,
// смотри»). В сумме это укладывается в пару фраз; жёсткие 12 слов браковали
// нормальные новостные хуки, поэтому лимит по факту — 20.
const HOOK_MAX_WORDS = 20;

/**
 * Вычищает из текста ссылки и сноски.
 *
 * С включённым веб-поиском модель дописывает к фразам источники — вида
 * `[mashagpt.ru](https://…/blog/…)`. В подписи это мусор, а в озвучке
 * катастрофа: синтезатор честно читает адрес вслух. Просьбы в промпте
 * недостаточно, поэтому чистим механически.
 */
export function stripSources(text: string): string {
  return (
    text
      // [подпись](адрес) → подпись, дальше подпись-домен уберётся ниже
      .replace(/\[([^\]]*)\]\((?:https?:\/\/|www\.)[^)]*\)/gi, "$1")
      .replace(/\((?:https?:\/\/|www\.)[^)]*\)/gi, " ")
      .replace(/(?:https?:\/\/|www\.)\S+/gi, " ")
      // Голый домен: «mashagpt.ru», «example.com».
      .replace(
        /\b(?:[a-z0-9-]+\.)+(?:ru|com|net|org|io|ai|me|dev|app|co|info|su|рф)\b/gi,
        " ",
      )
      .replace(/\[\d+\]|\[\s*\]|\(\s*\)/g, " ")
      // Осколки пунктуации после вырезанного: « . », «..», « ,».
      .replace(/\s+/g, " ")
      .replace(/\s+([,.!?;:…])/g, "$1")
      .replace(/([.!?])(?:\s*\1)+/g, "$1")
      .trim()
  );
}

function sanitizeScript(script: GeneratedScript): GeneratedScript {
  return {
    title: stripSources(script.title ?? ""),
    // Сцена пересобирается поле за полем, и overlay здесь терялся: он просто
    // не переписывался в новый объект, поэтому появляющиеся объекты не доходили
    // до сборки вообще — сценарист их предлагал, а в ролике их не было.
    scenes: script.scenes.map((scene) => ({
      caption: stripSources(scene.caption ?? ""),
      voiceoverText: stripSources(scene.voiceoverText ?? ""),
      ...(scene.overlay?.object
        ? {
            overlay: {
              object: stripSources(scene.overlay.object),
              word: scene.overlay.word,
              acrossCut: scene.overlay.acrossCut,
            },
          }
        : {}),
    })),
  };
}

// Приветствия и «в этом видео» в начале — главный убийца удержания, поэтому
// проверяем их отдельно от промпта: модель про запрет иногда забывает.
const WEAK_HOOK_OPENINGS =
  /^\s*(привет|здравствуй|здорово|салам|ассаламу|добрый\s+(день|вечер|утро)|доброе\s+утро|друзья|дорогие|уважаемые|итак|hello|hi\b|hey|в\s+этом\s+(видео|ролике)|сегодня\s+(я\s+)?(расскажу|поговорим)|меня\s+зовут)/i;

/**
 * Проверяет, годится ли первая сцена в качестве хука. Возвращает причину
 * отказа — её же отправляем модели, чтобы она переписала именно хук.
 */
export function hookProblem(scene: ScriptScene): string | undefined {
  const voiceover = scene.voiceoverText.trim();
  if (WEAK_HOOK_OPENINGS.test(voiceover)) {
    return "хук начинается с приветствия или с «в этом видео» — это отпугивает зрителя";
  }
  const words = voiceover.split(/\s+/).filter(Boolean).length;
  if (words > HOOK_MAX_WORDS) {
    return `в хуке ${words} слов, нужно не больше ${HOOK_MAX_WORDS}`;
  }
  if (scene.caption.split(/\s+/).filter(Boolean).length > 5) {
    return "подпись хука длиннее 5 слов";
  }
  return undefined;
}

// Рекламные обороты. Модель, получив бриф про продукт, легко скатывается в
// «наш бот умеет вот это» с первой же сцены — а зритель ради такого не
// смотрит. Ищем их во всех сценах, кроме последней: там призыв к действию
// уместен и обязателен.
// Внимание к \w: в JS он не включает кириллицу, поэтому окончания слов
// перебираются классом [а-яё] — иначе «по ссылке в описании» не находится.
const PROMO_PATTERNS: { re: RegExp; what: string }[] = [
  { re: /наш[а-яё]*\s+(бот|сервис|канал|приложени|платформ|нейросет)/i, what: "«наш бот/сервис»" },
  { re: /у\s+нас\s+(есть|можно|уже)/i, what: "«у нас есть»" },
  { re: /подписк|подпишись|подписыва/i, what: "подписка" },
  { re: /тариф|промокод|оформ(и|ите|ить)\s|пробн[а-яё]+\s+период/i, what: "тарифы или промокод" },
  { re: /ссылк[а-яё]*\s+(в|под)\s+(описании|шапке|профиле|видео)/i, what: "ссылка в описании" },
  { re: /переходи|перейди|жми|жмите|нажми|регистрируйся|зарегистрир/i, what: "призыв к действию" },
  { re: /бесплатн[а-яё]*\s+(доступ|пробуй|попробуй)/i, what: "«бесплатный доступ»" },
];

// Пустой восторг и связки без содержания. С ними ролик звучит бодро, но
// зритель не узнаёт ничего — именно так выглядит «сценарий ни о чём».
const FILLER_PATTERNS: { re: RegExp; what: string }[] = [
  {
    re: /красот[аы]!|чист(ый|ое)\s+кайф|бомбическ|это\s+магия|огонь!|вау|кайф!|сказка|мечта!/i,
    what: "пустой восторг",
  },
  {
    re: /легко\s+и\s+просто|проще\s+некуда|меняют?\s+дело|в\s+два\s+клика|на\s+раз-два|без\s+проблем!/i,
    what: "штамп вместо пользы",
  },
  {
    re: /как\s+говорится|итак,?\s+поехали|начнём\s+с\s+того|сначала\s+мы\s|, да\?/i,
    what: "связка без содержания",
  },
];

// Проценты, «в N раз» и «за N минут» в ролике почти всегда выдуманы, а звучат
// как реклама. Границу слова здесь нельзя писать через \b: в JS он опирается
// на латинский \w, и перед кириллической буквой границы просто нет — нужен
// явный запрет предыдущей буквы. Числа считаем и цифрами, и словами: «в пять
// раз быстрее» — такая же непроверяемая цифра, как «в 5 раз».
const NUMBER_WORD =
  "\\d+|два|две|три|четыре|пять|шесть|семь|восемь|девять|десять";
const FAKE_STATS = new RegExp(
  `\\d+\\s?%|(?<![а-яё])в\\s+(?:${NUMBER_WORD})\\s+раз|(?<![а-яё])за\\s+(?:${NUMBER_WORD})\\s+(?:минут|секунд|час)`,
  "i",
);

// Латинское название с заглавной: Midjourney, GPT-5.4, Sora 2, ElevenLabs.
const TOOL_NAME = /\b[A-Z][A-Za-z0-9]+(?:[.\-]\d+(?:\.\d+)?)?\b/;
const MAX_TOOL_SCENES = 2;

/**
 * Ролик не должен превращаться в перечисление инструментов: «Midjourney
 * сделает раскадровку», «Suno напишет музыку» — это список названий, из
 * которого зритель не выносит ни одного действия.
 */
export function toolListProblem(script: GeneratedScript): string | undefined {
  // Хук и финал не считаем: там название бывает уместно.
  const body = script.scenes.slice(1, -1);
  if (body.length < 3) return undefined;
  const named = body.filter((scene) => TOOL_NAME.test(scene.caption)).length;
  if (named > MAX_TOOL_SCENES && named / body.length > 0.4) {
    return (
      `${named} из ${body.length} сцен середины — это названия инструментов, ` +
      "а не польза: нужно показать, что именно делать, а не перечислять сервисы"
    );
  }
  return undefined;
}

/**
 * Ищет пустые фразы и выдуманные цифры в середине ролика.
 */
export function fillerProblem(script: GeneratedScript): string | undefined {
  const found: string[] = [];
  script.scenes.slice(0, -1).forEach((scene, index) => {
    const text = `${scene.caption} ${scene.voiceoverText}`;
    for (const { re, what } of FILLER_PATTERNS) {
      if (re.test(text)) found.push(`сцена ${index + 1} — ${what}`);
    }
    if (FAKE_STATS.test(text)) {
      found.push(`сцена ${index + 1} — непроверяемая цифра`);
    }
  });
  if (found.length === 0) return undefined;
  return `в сценах есть вода вместо конкретики (${found.slice(0, 5).join("; ")})`;
}

/**
 * Проверяет, что реклама осталась только в финале. Возвращает причину отказа —
 * её же отправляем модели на переписывание.
 */
export function promoProblem(script: GeneratedScript): string | undefined {
  const body = script.scenes.slice(0, -1);
  const found: string[] = [];
  body.forEach((scene, index) => {
    const text = `${scene.caption} ${scene.voiceoverText}`;
    for (const { re, what } of PROMO_PATTERNS) {
      if (re.test(text)) found.push(`сцена ${index + 1} — ${what}`);
    }
  });
  if (found.length === 0) return undefined;
  return (
    `реклама попала в середину ролика (${found.slice(0, 5).join("; ")}), ` +
    "а продукт должен упоминаться только в последней сцене"
  );
}

// Тупиковые концовки: ролик кончается тем, что «учёные работают над этим».
// Зритель не получает ни вывода, который можно применить, ни мнения, с которым
// можно спорить, ни факта, которым хочется поделиться, — то есть ни одной
// причины сохранить, переслать или прокомментировать. А это ровно те сигналы,
// по которым площадка решает, показывать ролик дальше.
//
// Проверяем последнюю сцену ПЕРЕД призывом: содержательный финал именно там,
// в самой последней идёт призыв к действию.
const DEAD_END_PATTERNS: { re: RegExp; what: string }[] = [
  { re: /учён[ыои][а-яё]*\s+(ищут|работают|бьются|пытаются)/i, what: "«учёные работают над этим»" },
  { re: /инженер[а-яё]*\s+(ищут|работают|бьются|пытаются)/i, what: "«инженеры ищут способы»" },
  { re: /(время|будущее)\s+покажет/i, what: "«время покажет»" },
  { re: /непрост[а-яё]+\s+задач/i, what: "«непростая задача»" },
  { re: /посмотрим,?\s+(что|как)\s+(будет|получится|выйдет)/i, what: "«посмотрим, что будет»" },
  { re: /пока\s+(что\s+)?(неясно|непонятно|никто не знает)/i, what: "«пока неясно»" },
  { re: /вопрос\s+остаётся\s+открытым/i, what: "«вопрос остаётся открытым»" },
  { re: /работа\s+(всё ещё\s+)?ид[её]т/i, what: "«работа идёт»" },
];

/**
 * Содержательный финал должен давать зрителю вывод, а не разводить руками.
 */
export function deadEndProblem(script: GeneratedScript): string | undefined {
  // Нужны хотя бы призыв и одна содержательная сцена перед ним.
  if (script.scenes.length < 2) return undefined;
  const last = script.scenes[script.scenes.length - 2];
  const text = `${last.caption} ${last.voiceoverText}`;
  const hit = DEAD_END_PATTERNS.find(({ re }) => re.test(text));
  if (!hit) return undefined;
  return (
    `ролик кончается ничем: ${hit.what} — зрителю нечего унести, ` +
    "нечем поделиться и не о чем спорить"
  );
}

// Крупные числа: они и есть крючок. В присланном ролике «1287 мегаватт-часов,
// это как сто домов за год» стояло на двенадцатой секунде — к этому моменту
// половина зрителей уже ушла. Если в ролике есть яркая цифра, она обязана
// звучать в первой сцене.
const SCALE_WORDS = /(миллион|миллиард|триллион|тысяч|мегаватт|киловатт|терабайт|петабайт|процент)/i;

function hasStrikingNumber(text: string): boolean {
  if (SCALE_WORDS.test(text)) return true;
  // Пробел внутри числа («1 287») склеиваем, иначе крупное число распадётся
  // на два мелких. Пробелы между разными числами при этом не трогаем.
  const joined = text.replace(/(\d)[\u00A0\s]+(\d)/g, "$1$2");
  for (const run of joined.match(/\d+/g) ?? []) {
    if (run.length >= 5) return true;
    // Четыре знака — крупно, но только если это не год: «в 2026 году» есть в
    // каждом втором ролике про ИИ, и считать его крючком нельзя.
    if (run.length === 4) {
      const value = Number(run);
      if (value < 1900 || value > 2099) return true;
    }
  }
  return false;
}

/**
 * Яркая цифра должна быть в хуке, а не в середине.
 */
export function hookNumberProblem(script: GeneratedScript): string | undefined {
  const [hook, ...rest] = script.scenes;
  if (!hook || rest.length === 0) return undefined;
  if (hasStrikingNumber(`${hook.caption} ${hook.voiceoverText}`)) return undefined;

  const found = rest.findIndex((scene) =>
    hasStrikingNumber(`${scene.caption} ${scene.voiceoverText}`),
  );
  if (found < 0) return undefined;
  return (
    `самая яркая цифра ролика лежит в сцене ${found + 2}, а не в хуке — ` +
    "к ней зритель может и не досмотреть"
  );
}

// Слабый призыв. «Там много интересного» — это не предложение, а вежливость:
// зритель не узнаёт ни что он получит, ни почему сейчас.
const VAGUE_CTA = /(там|тут)\s+(много|полно)\s+(интересного|полезного|всего)|там\s+всё\s+есть|не\s+пожалеешь|заходи[,\s]|будет\s+интересно/i;
// Конкретика, ради которой человек нажимает: цена, скорость, отсутствие
// барьера или прямое «попробуй».
const CONCRETE_OFFER = /бесплатн|без\s+(регистрации|карты|подписки)|прямо\s+сейчас|за\s+(минуту|пару\s+минут|секунды)|попробуй|затест|проверь\s+сам|первый\s+[а-яё]+\s+бесплатн/i;
// Призыв длиннее этого перестаёт быть призывом: в присланном ролике он занял
// двенадцать секунд, то есть шестую часть хронометража.
const CTA_MAX_WORDS = 22;

/**
 * Последняя сцена — единственное место, где мы что-то просим у зрителя.
 * Значит она обязана быть конкретной и короткой.
 */
export function ctaProblem(script: GeneratedScript): string | undefined {
  const cta = script.scenes[script.scenes.length - 1];
  if (!cta) return undefined;
  const text = `${cta.caption} ${cta.voiceoverText}`;
  const found: string[] = [];

  const vague = text.match(VAGUE_CTA);
  if (vague) found.push(`«${vague[0].trim()}» ничего не обещает`);
  if (!CONCRETE_OFFER.test(text)) {
    found.push("нет конкретного предложения (бесплатно, без регистрации, попробуй сейчас)");
  }
  const words = cta.voiceoverText.trim().split(/\s+/).filter(Boolean).length;
  if (words > CTA_MAX_WORDS) {
    found.push(`призыв растянут на ${words} слов, нужно не больше ${CTA_MAX_WORDS}`);
  }

  if (found.length === 0) return undefined;
  return `слабый призыв в финале: ${found.join("; ")}`;
}

// Устаревшие примеры. Ролик про ИИ, где флагманский пример — GPT-3, читается
// как позавчерашний: аудитория, которая следит за темой, датирует материал
// мгновенно. Список приходится обновлять руками — других способов нет, а
// вреда от него меньше, чем от ролика с примером пятилетней давности.
const STALE_NAMES =
  /(GPT-3(\.5)?|ChatGPT-3|DALL-?E\s?2|Midjourney\s?v?[45]|Stable\s?Diffusion\s?1\.5|Llama\s?2|Claude\s?2)(?![\d.])/i;

/** Пример из позапрошлого поколения старит ролик целиком. */
export function staleProblem(script: GeneratedScript): string | undefined {
  const found: string[] = [];
  script.scenes.forEach((scene, index) => {
    const match = `${scene.caption} ${scene.voiceoverText}`.match(STALE_NAMES);
    if (match) found.push(`сцена ${index + 1} — ${match[0]}`);
  });
  if (found.length === 0) return undefined;
  return (
    `в ролике устаревшие примеры (${found.slice(0, 3).join("; ")}) — ` +
    "они датируют материал прошлым поколением"
  );
}

// Скорость речи синтезатора. Было 2.4, стало 2.1 — по замеру на настоящем
// ролике: он вышел 71 секунда против бюджета в 60, то есть на 19% длиннее.
// Ошибаться в эту сторону дороже, чем в обратную: недобор длины никому не
// мешает, а перебор ломает лимит, и подрезать его уже нечем — fitToBudget
// умеет только урезать паузы, а это доли секунды на сцену.
const WORDS_PER_SECOND = 2.1;

// Ритм. В присланном референсе картинка меняется каждые полторы-три секунды;
// у нас же сцена была «законченной мыслью» на 25-45 слов, то есть 12-20
// секунд одного неподвижного кадра. Замер на реальном ролике: шесть сцен на
// 69 секунд, один кадр висел 15 секунд с покадровой разницей 0.06 из 255.
// При такой раскладке вся работа над переходами не видна — их всего шесть на
// ролик.
//
// Поэтому сцена теперь — это КАДР, а не мысль: реплика может обрываться на
// середине фразы и продолжаться в следующей сцене.
const MIN_WORDS_PER_SCENE = 8;
const MAX_WORDS_PER_SCENE = 14;
// Столько же слов, но последней сцене с призывом к действию можно вдвое
// больше: разрывать призыв пополам незачем, а ещё это столкнулось бы с
// проверкой на рекламу, которая освобождает только последнюю сцену.
const CTA_WORDS_FACTOR = 2;

/** Сколько слов озвучки укладывается в ролик заданной длины. */
export function wordBudget(maxVideoSeconds: number): number {
  return Math.floor(maxVideoSeconds * WORDS_PER_SECOND);
}

/**
 * Сколько сцен нужно минимум, чтобы кадр не висел дольше нескольких секунд.
 * Ограничено сверху MAX_SCENES: при маленьком лимите просить больше сцен, чем
 * разрешено, — значит просить невозможного.
 */
export function minSceneCount(maxVideoSeconds: number): number {
  return Math.min(
    Math.max(Math.ceil(wordBudget(maxVideoSeconds) / MAX_WORDS_PER_SCENE), 4),
    config.maxScenes,
  );
}

