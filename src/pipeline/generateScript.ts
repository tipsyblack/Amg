/**
 * Сценарий с проверками качества. Найденные проблемы уходят модели одной
 * правкой — ровно одна попытка, чтобы не жечь запросы в цикле. Даже если
 * правка не помогла, сценарий отдаётся: пустой результат хуже несовершенного.
 */
export async function generateCheckedScript(
  brief: string,
  revision?: ScriptRevision,
  maxVideoSeconds?: number,
  model?: string,
): Promise<CheckedScript> {
  const first = await generateScript(brief, revision, maxVideoSeconds, model);

  // Структурные проверки бесплатны, поэтому идут первыми. Критик стоит
  // генерации — зовём его один раз, вместе с ними, а не после.
  const structural = scriptProblems(first.script, maxVideoSeconds);
  const review = await reviewScript(first.script, brief, model);
  const problems = [
    ...structural,
    ...review.problems.map(formatReviewProblem),
  ];

  if (problems.length === 0) {
    return {
      ...first,
      fixes: [],
      reviewUnavailable: review.unavailable,
      remaining: [],
    };
  }

  const instructions = FIX_INSTRUCTIONS.filter(({ key }) =>
    problems.some((p) => p.includes(key)),
  ).map(({ instruction }) => instruction);

  const fixed = await generateScript(
    brief,
    {
      previousScript: first.script,
      feedback: `${problems.join("; ")}. ${instructions.join(" ")} ` +
        "Остальные сцены оставь как есть.",
    },
    maxVideoSeconds,
    model,
  );

  const script = fixed.script.scenes.length > 0 ? fixed.script : first.script;
  return {
    script,
    webSearchUnavailable: first.webSearchUnavailable,
    reviewUnavailable: review.unavailable,
    fixes: problems,
    // Перепроверяем то, что можно проверить бесплатно. Правка — просьба к
    // модели, а не гарантия: она вполне может не сработать, и знать об этом
    // нужно до сборки, а не после просмотра.
    remaining: scriptProblems(script, maxVideoSeconds),
  };
}
