import { STYLE_PROMPT } from "./generateImage";
import { TAP_KINDS, TAP_ZONES, tapKindFor, tapZone, type TapKind } from "../remotion/tap";

/**
 * Гайды по боту: скриншот превращается в кадр нашего стиля.
 *
 * Это ВТОРОЙ вид роликов, и устроен он наоборот к новостному. Там модель
 * придумывает и текст, и картинку; здесь текст пишет человек — по реплике на
 * слайд, — а картинка берётся из его же скриншота. Поэтому здесь нет ни
 * подбора темы, ни проверок хука и призыва: судить чужой сценарий нашими
 * правилами для новостей значит браковать инструкцию за то, что она инструкция.
 *
 * ГЛАВНОЕ ОТЛИЧИЕ — НАДПИСИ. В новостных роликах текст в кадре запрещён
 * (NO_TEXT_RULE): он дублировал бы субтитры, и модель рисует его с ошибками.
 * В гайде наоборот: без названий кнопок и полей кадр перестаёт быть
 * инструкцией. Поэтому запрет сюда не идёт, а вместо него стоит требование
 * переносить надписи ДОСЛОВНО.
 *
 * Про риск сказано честно и в промпте, и в чате: кириллицу картиночные модели
 * рисуют хуже латиницы, и слайд с длинной подписью может выйти с кракозябрами.
 * Лечится это не промптом, а глазами — каждый слайд показывается на
 * согласовании до сборки.
 */

/** Как перерисовать экран, чтобы он остался экраном этого же бота. */
export const GUIDE_STYLE_PROMPT = `${STYLE_PROMPT}

ЭТО ПЕРЕРИСОВКА ЭКРАНА, А НЕ НОВАЯ КАРТИНКА. На вход дан скриншот интерфейса.
Нарисуй его заново в описанном выше стиле, сохранив устройство экрана:

- РАСПОЛОЖЕНИЕ КАК В ОРИГИНАЛЕ: что сверху — то сверху, кнопки там же, где
  были, порядок сообщений и полей не меняется. Зритель будет искать это глазами
  в настоящем боте, и кадр обязан совпадать с тем, что он там увидит.
- НАДПИСИ ПЕРЕНОСИ ДОСЛОВНО, буква в букву: названия кнопок, команды со слэшем,
  подписи полей, ключевые фразы сообщений. Не переводи, не сокращай, не
  придумывай новых. Это инструкция — неверная надпись в ней хуже, чем никакой.
- УБЕРИ ЛИШНЕЕ: строку состояния телефона, клавиатуру, часы, аватарки,
  посторонние сообщения, рекламу. Оставь то, о чём идёт речь в этом кадре.
- УПРОСТИ ОСТАЛЬНОЕ: длинные тексты, которые не важны для шага, покажи
  несколькими короткими строками-заглушками без букв. Читаться должно главное.
- КРУПНО: интерфейс занимает почти весь кадр. Не рисуй телефон целиком с
  рамками и кнопками — нужен сам экран.
- Кадр вертикальный, пропорции 3:4.`;

/**
 * Промпт одного слайда.
 *
 * @param narration реплика этого слайда — по ней модель понимает, что здесь
 *   главное. Текст человека, поэтому идёт как есть.
 * @param note необязательное указание «что выделить» — когда реплика говорит
 *   об одном, а показать надо другое.
 */
export function buildGuidePrompt(
  narration: string,
  note?: string,
  styleNotes?: string,
): string {
  return (
    GUIDE_STYLE_PROMPT +
    (styleNotes ? `\n\nЗаметки о стиле: ${styleNotes}` : "") +
    `\n\nО чём этот кадр (по нему решай, что выделить крупнее и ярче): ${narration}` +
    (note ? `\n\nОтдельно: ${note}` : "")
  );
}

export interface GuideSlide {
  /** Скриншот на диске. */
  file: string;
  /** Реплика этого слайда — её произносит Шамиль. */
  text: string;
  /** Что выделить, если реплика этого не говорит. */
  note?: string;
  /** Куда и чем показать нажатие. Разбирается из пометки в реплике. */
  tap?: { kind: TapKind; xPercent: number; yPercent: number };
}

/**
 * Подпись слайда для согласования. На экране она не показывается (весь текст
 * несут субтитры), нужна человеку в списке — чтобы понимать, о каком слайде
 * речь, не перечитывая реплику целиком.
 */
export function slideCaption(text: string, max = 6): string {
  const words = text.trim().split(/\s+/).filter(Boolean);
  const short = words.slice(0, max).join(" ");
  return words.length > max ? `${short}…` : short;
}

// Реплика слайда. Нижняя граница — чтобы кадр не мелькал: меньше трёх слов
// зритель не успевает даже прочитать субтитр. Верхняя — чтобы один экран не
// висел полминуты; если сказать надо больше, это два слайда, и второй кадр
// можно показать тот же.
export const MIN_SLIDE_WORDS = 3;
export const MAX_SLIDE_WORDS = 60;

export interface GuideProblem {
  slide: number;
  message: string;
}

/**
 * Что не так со слайдами. Проверяется ДО отрисовки: каждый слайд — это платная
 * генерация картинки, и находить пустую реплику после оплаты обидно.
 */
export function guideProblems(slides: GuideSlide[]): GuideProblem[] {
  const problems: GuideProblem[] = [];
  slides.forEach((slide, index) => {
    const words = slide.text.trim().split(/\s+/).filter(Boolean).length;
    if (words === 0) {
      problems.push({ slide: index + 1, message: "нет реплики — озвучивать нечего" });
      return;
    }
    if (words < MIN_SLIDE_WORDS) {
      problems.push({
        slide: index + 1,
        message: `реплика из ${words} слов — кадр мелькнёт и пропадёт`,
      });
    }
    if (words > MAX_SLIDE_WORDS) {
      problems.push({
        slide: index + 1,
        message:
          `реплика из ${words} слов — один экран провисит очень долго. ` +
          "Разбейте на два слайда, картинку можно взять ту же",
      });
    }
  });
  return problems;
}

/**
 * Сценарий из слайдов — в том же виде, в каком его ждёт сборка ролика.
 *
 * Поле visual остаётся пустым намеренно: картинка уже есть, придумывать ей
 * описание нечего. Overlay и swap тоже не нужны — в гайде движение только
 * мешает читать экран.
 */
export function guideScript(
  title: string,
  slides: GuideSlide[],
): { title: string; scenes: { caption: string; voiceoverText: string }[] } {
  return {
    title,
    scenes: slides.map((slide) => ({
      caption: slideCaption(slide.text),
      voiceoverText: slide.text.trim(),
    })),
  };
}


/**
 * Пометка о нажатии внутри реплики: `[клик: внизу справа]`.
 *
 * Почему прямо в тексте, а не отдельным вопросом на каждый слайд: слайды
 * присылают пачкой с телефона, и лишний вопрос после каждого скриншота
 * превратил бы съёмку гайда в допрос. Пометка пишется там же, где реплика, и
 * ВЫРЕЗАЕТСЯ из неё — иначе синтезатор честно прочитает «квадратная скобка
 * клик» вслух.
 *
 * Понимаются зоны словами («внизу справа»), проценты («30 70») и вид
 * подсказки («обводка»). Ничего не указано — нижняя середина: в телеграм-боте
 * почти всё нажимаемое живёт там.
 */
export interface TapSpec {
  kind: TapKind;
  xPercent: number;
  yPercent: number;
}

const KIND_WORDS: Record<string, TapKind> = {
  курсор: "cursor",
  стрелка: "arrow",
  обводка: "frame",
  рамка: "frame",
  кольцо: "ring",
  круг: "ring",
  волна: "ripple",
  касание: "ripple",
};

/** Убирает пометку из реплики и возвращает то, что в ней было сказано. */
export function parseTapTag(
  text: string,
  index = 0,
): { text: string; tap?: TapSpec } {
  const off = text.match(/\[\s*(?:без\s+клика|без\s+подсказки)\s*\]/i);
  if (off) {
    return { text: text.replace(off[0], " ").replace(/\s+/g, " ").trim() };
  }

  const tag = text.match(/\[\s*(?:клик|тап)\s*:?\s*([^\]]*)\]/i);
  const clean = tag
    ? text.replace(tag[0], " ").replace(/\s+/g, " ").trim()
    : text.trim();
  const inside = (tag?.[1] ?? "").toLowerCase().trim();

  // Вид подсказки: если не назван, чередуется по номеру слайда — один и тот же
  // курсор десять кадров подряд перестаёт читаться как подсказка.
  const kindWord = Object.keys(KIND_WORDS).find((word) => inside.includes(word));
  const kind = tapKindFor(index, kindWord ? KIND_WORDS[kindWord] : undefined);

  // Проценты: «30 70». Берём только если оба числа в пределах кадра.
  const numbers = inside.match(/(\d{1,3})\s*[,\s]\s*(\d{1,3})/);
  if (numbers) {
    const x = Number(numbers[1]);
    const y = Number(numbers[2]);
    if (x >= 0 && x <= 100 && y >= 0 && y <= 100) {
      return { text: clean, tap: { kind, xPercent: x, yPercent: y } };
    }
  }

  // Зона словами. Ищем самое длинное совпадение: «внизу справа» должно
  // выиграть у «внизу».
  const zoneWord = Object.keys(TAP_ZONES)
    .filter((zone) => inside.includes(zone))
    .sort((a, b) => b.length - a.length)[0];
  const point = tapZone(zoneWord);
  return { text: clean, tap: { kind, xPercent: point.x, yPercent: point.y } };
}

/** Список видов подсказки для подсказки в чате. */
export const TAP_WORDS = Object.keys(KIND_WORDS);
export { TAP_KINDS };
