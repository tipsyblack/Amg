/**
 * Тона для сцен с маскотом: джин синий, и на холодном фоне он сливается.
 * Замер это подтверждает — три «синие» картинки нашего ролика (204-218°) как
 * раз его, и фон там уже отдал синеву.
 */
const CHARACTER_TONES = ["sand", "paper", "coral"];
/** С маскотом нужен он сам, а не пустота и не вид сверху на предметы. */
const CHARACTER_SHOTS = ["mid", "close"];

export interface SceneLook {
  tone: SceneTone;
  shot: SceneShot;
}

/**
 * Задание для сцены.
 *
 * @param index номер сцены
 * @param withCharacter в кадре маскот — набор тонов и планов сужается
 * @param seed отличает ролики друг от друга: иначе хук каждого ролика был бы
 *   песочным, а ролики завода похожи друг на друга так же, как сцены внутри
 *   одного. Обычно это номер по названию ролика — оно не меняется между
 *   попытками, поэтому перерисовка одной сцены не сдвигает остальные.
 * @param attempt номер перерисовки. Сдвиг берётся из списка безопасных (см.
 *   shiftFor): перерисованная сцена не должна совпасть ни с тем, что уже
 *   отвергли, ни с соседями по ролику.
 */
export function sceneLook(
  index: number,
  { withCharacter = false, seed = 0, attempt = 0 } = {},
): SceneLook {
  const tones = withCharacter
    ? SCENE_TONES.filter((t) => CHARACTER_TONES.includes(t.id))
    : SCENE_TONES;
  const shots = withCharacter
    ? SCENE_SHOTS.filter((s) => CHARACTER_SHOTS.includes(s.id))
    : SCENE_SHOTS;

  const step = index + seed;
  return {
    tone: tones[mod(step + shiftFor(attempt, tones.length), tones.length)],
    shot: shots[mod(step + shiftFor(attempt, shots.length), shots.length)],
  };
}

/**
 * Насколько сдвинуть выбор при перерисовке.
 *
 * Годятся не любые сдвиги. Сдвиг 0 (и кратный длине списка) вернул бы то же
 * самое, что уже забраковали; сдвиг на 1 и на length-1 дал бы то же, что у
 * соседней сцены. Остальные безопасны, и перебираем их по кругу.
 *
 * Когда безопасных сдвигов нет — а это ровно случай сцен с маскотом, где
 * список сужен до трёх тонов и двух планов, — сдвигаем на номер попытки.
 * Соседи у таких сцен (хук и финал) выбираются из ПОЛНОГО списка, так что
 * совпасть с ними всё равно нельзя, а вот повторить только что забракованную
 * картинку — можно, и это худший из исходов.
 */
function shiftFor(attempt: number, size: number): number {
  if (attempt <= 0) return 0;
  const safe: number[] = [];
  for (let d = 2; d <= size - 2; d++) safe.push(d);
  if (safe.length === 0) return attempt;
  return safe[(attempt - 1) % safe.length];
}

function mod(value: number, size: number): number {
  return ((value % size) + size) % size;
}

/**
 * Номер ролика по названию. Нужен только чтобы разные ролики начинались с
 * разного тона, поэтому годится самая простая сумма кодов.
 */
export function seedFromTitle(title: string): number {
  let sum = 0;
  for (let i = 0; i < title.length; i++) sum += title.charCodeAt(i);
  return sum;
}

/**
 * Задание словами — этот кусок уходит в промпт картинки.
 *
 * Тон и план тут не равны, и это сказано прямо. Цвет содержанию сцены
 * противоречить не может: любую сцену можно нарисовать в песочном или в
 * ночном. А план — может: «конвейер везёт огромные портреты» и «просторный
 * план, деталей минимум» друг друга исключают, и такое противоречие модель
 * разрешает как попало. Поэтому у плана есть явный выход, а у тона нет.
 */
export function lookPrompt(look: SceneLook): string {
  return (
    `${look.tone.prompt}\n${look.shot.prompt}\n` +
    "Тон кадра обязателен. План — предпочтительный; если сцена в него совсем " +
    "не ложится, сними её ближайшим подходящим."
  );
}

/** Короткая пометка для чата и логов: видно, что сцены заданы разными. */
export function lookLabel(look: SceneLook): string {
  return `${look.tone.id}/${look.shot.id}`;
}
