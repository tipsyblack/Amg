import { config } from "./config";
import { getImageModel } from "./imageModels";
import { runKieTask } from "./kie";

// Стиль сцены выведен из присланного референс-видео: плоская векторная
// иллюстрация, толстый чёрный контур, приглушённая пастельная палитра,
// лёгкий юмористический тон. Персонаж — фирменный маскот "Pro Neiro":
// джин Шамиль (Шама). Правьте под свой конкретный референс/бренд-бук.
export const STYLE_PROMPT = `Плоская векторная иллюстрация в стиле коротких
объясняющих видео для соцсетей: толстый ровный чёрный контур, приглушённая
пастельная палитра, простые обтекаемые формы, лёгкий юмористический тон,
современный flat-cartoon стиль. Вертикальный кадр, сцена занимает весь кадр,
без текста и надписей на самой картинке.

Главный персонаж — джин по имени Шамиль (Шама), фирменный маскот бренда
"Pro Neiro": синяя кожа, чёрные волосы собраны в хвост с золотым зажимом,
острые уши, тонкие усы и аккуратная бородка, золотая серьга-кольцо,
мускулистый торс, красный жилет с золотой окантовкой, золотые браслеты на
запястьях. Обычно появляется в виде клубящегося дымного шлейфа/силуэта —
как будто выходит из волшебной лампы. Первое приложенное изображение —
эталон внешности персонажа: сохраняй его лицо, причёску, одежду и цветовую
гамму на всех сценах, меняя только позу, ракурс, окружение и действие по
смыслу конкретной сцены. Лампу с логотипом в кадр не добавляй.`;

interface GenerateSceneImageOptions {
  prompt: string;
  outFile: string;
  // Ссылка на картинку предыдущей сцены — передаётся вторым референсом,
  // чтобы окружение и палитра не "уплывали" между сценами.
  previousSceneUrl?: string;
  // Ключ модели из IMAGE_MODELS (выбор в боте); пусто = модель по умолчанию.
  modelKey?: string;
}

/**
 * Генерирует иллюстрацию сцены через Kie.ai и сохраняет её в outFile.
 * Возвращает публичную ссылку на результат — её передаём следующей сцене.
 */
export async function generateSceneImage({
  prompt,
  outFile,
  previousSceneUrl,
  modelKey,
}: GenerateSceneImageOptions): Promise<string> {
  const spec = getImageModel(modelKey);
  const imageUrls = [config.characterReferenceUrl];
  if (previousSceneUrl) {
    imageUrls.push(previousSceneUrl);
  }

  return runKieTask({
    model: spec.model,
    input: spec.buildInput(prompt, imageUrls),
    outFile,
    label: `иллюстрация сцены, модель ${spec.model}`,
  });
}
