import type { GeneratedScript } from "./generateScript";

/**
 * Ролик, который пересказывает сам себя.
 *
 * Разбор присланного ролика: пять мыслей растянуты на двенадцать кадров, и
 * вторая половина повторяет первую. «Искать дизайнера — долго и дорого» на 9-й
 * секунде и «зачем платить, ждать, если можно сделать самому быстро» на 40-й —
 * это одно и то же. Зритель слышит уже сказанное и перестаёт чувствовать
 * движение вперёд: ролик не идёт, а топчется. Именно это заказчик и назвал
 * «как-то не связано».
 *
 * ЧТО ЭТА ПРОВЕРКА ЛОВИТ, А ЧТО НЕТ. Здесь ловится ДОСЛОВНЫЙ повтор — когда
 * две далёкие сцены собраны из одних и тех же слов. Пересказ теми же словами
 * находится, пересказ ДРУГИМИ словами — нет: «долго и дорого» и «зачем
 * платить и ждать» не имеют ни одного общего корня, хотя это одна мысль.
 *
 * Так и задумано, и это соответствует разделению из README: структура
 * проверяется кодом, смысл — моделью-критиком. Регулярка не должна делать вид,
 * что понимает смысл. Пересказ другими словами ловит критик, у него для этого
 * есть отдельный пункт чек-листа.
 */

// Слова, которые ничего не говорят о содержании сцены. Без этого списка любые
// две сцены «совпадали» бы по «это», «как», «что».
const STOP_WORDS = new Set([
  "и", "а", "но", "да", "или", "либо", "то", "же", "ли", "бы", "не", "ни",
  "в", "во", "на", "за", "из", "от", "до", "по", "с", "со", "к", "ко", "у",
  "о", "об", "про", "для", "при", "над", "под", "без", "через", "между",
  "это", "этот", "эта", "эти", "тот", "та", "те", "там", "тут", "здесь",
  "как", "так", "что", "чем", "чего", "кто", "кого", "где", "когда", "почему",
  "уже", "ещё", "еще", "вот", "всё", "все", "весь", "вся", "очень", "просто",
  "теперь", "потом", "сейчас", "тогда", "если", "чтобы", "зачем", "пока",
  "ты", "вы", "он", "она", "они", "мы", "я", "его", "её", "ее", "их", "им",
  "тебе", "тебя", "вам", "нам", "себе", "себя", "свой", "своя", "свои",
  "быть", "есть", "был", "была", "было", "были", "будет", "будут",
  "мочь", "может", "можно", "нужно", "надо", "нет", "да",
  "один", "одна", "одно", "два", "три", "раз",
]);

// Огрубление словоформ до корня: «дизайнерам», «дизайнера» и «дизайнер»
// должны считаться одним словом, иначе повтор не виден. Окончания сняты по
// длине — сначала длинные, иначе «ами» никогда не сработает после «и».
//
// Это НЕ морфология, а грубое отсечение хвоста. Ошибки тут неизбежны, поэтому
// порог срабатывания стоит на двух общих корнях, а не на одном: одно случайное
// совпадение корней ничего не значит.
const ENDINGS = [
  "ениями", "ениям", "ениях", "ением", "ения", "ение", "ений",
  "ами", "ями", "ого", "его", "ому", "ему", "ыми", "ими", "ешь", "ишь",
  "ся", "сь",
  "ах", "ях", "ов", "ев", "ей", "ий", "ый", "ая", "яя", "ое", "ее", "ие",
  "ые", "ем", "ом", "ам", "ям", "ах", "ух", "ат", "ят", "ет", "ит", "ут",
  "ют", "ла", "ло", "ли", "ть", "но", "на",
  "а", "я", "о", "е", "у", "ю", "ы", "и", "й", "ь",
];

// Ниже трёх букв корень перестаёт что-либо значить: «эт», «сд», «жд»
// совпадали бы у чего угодно.
const MIN_STEM = 3;

export function stem(word: string): string {
  const w = word.toLowerCase().replace(/ё/g, "е");
  for (const ending of ENDINGS) {
    if (w.length - ending.length >= MIN_STEM && w.endsWith(ending)) {
      return w.slice(0, -ending.length);
    }
  }
  return w;
}

/** Значимые корни реплики: без служебных слов и без цифр. */
export function contentStems(text: string): Set<string> {
  const stems = new Set<string>();
  for (const raw of text.toLowerCase().split(/[^а-яёa-z0-9]+/)) {
    if (!raw || STOP_WORDS.has(raw) || /^\d+$/.test(raw)) continue;
    if (raw.length < 3) continue;
    const s = stem(raw);
    if (s.length >= MIN_STEM) stems.add(s);
  }
  return stems;
}

// Порог выведен по корпусу, а не назначен. На семи здоровых сценариях самое
// сильное пересечение далёких сцен — ДВА общих корня («ты платишь пяти
// сервисам» и «считай не по сервисам, а по задачам»: сервис, дела). Это
// нормально: у ролика есть предмет, и его слова законно встречаются в разных
// сценах. На сценарии из присланного ролика пересечение — ТРИ корня
// («зачем ждать, пока сделают, сделай сам» и «зачем платить, ждать, если
// можно сделать самому быстро»: жда, сдела, сам).
//
// Поэтому порог — три. Запас над здоровым корпусом ровно в одно слово, и
// корпус здесь главная защита: если однажды нормальный сценарий начнёт
// спотыкаться об эту проверку, поднимать порог нельзя, не посмотрев, не стал
// ли он и правда повторяться.
const SHARED_STEMS_LIMIT = 3;

// Второе условие: общие слова должны составлять БОЛЬШУЮ ЧАСТЬ меньшей из двух
// сцен. Без него длинная сцена могла бы набрать три случайных совпадения на
// пустом месте. У пары из ролика эта доля 100% — вся сцена «зачем ждать, пока
// сделают, сделай сам» целиком состоит из слов, которые звучат ещё раз.
const SHARED_SHARE_LIMIT = 0.6;

// Соседние сцены проверять нельзя: сцена — это КАДР, а не мысль, и фраза
// сознательно продолжается из сцены в сцену. Общие слова у соседей — признак
// связности, а не повтора. Поэтому смотрим только сцены, разнесённые по ролику.
const MIN_DISTANCE = 2;

/**
 * Две далёкие сцены, собранные из одних и тех же слов.
 *
 * Слова темы (они же в заголовке) не считаются: ролик про нейросети обязан
 * говорить «нейросеть» в разных сценах, и ставить это в вину — значит
 * требовать синонимов там, где нужен один термин.
 */
export function repeatProblem(script: GeneratedScript): string | undefined {
  const titleStems = contentStems(script.title ?? "");
  const scenes = script.scenes.map((scene) => {
    const stems = contentStems(scene.voiceoverText);
    for (const t of titleStems) stems.delete(t);
    return stems;
  });

  for (let i = 0; i < scenes.length; i++) {
    for (let j = i + MIN_DISTANCE; j < scenes.length; j++) {
      const shared = [...scenes[i]].filter((s) => scenes[j].has(s));
      const share = shared.length / Math.min(scenes[i].size, scenes[j].size);
      if (shared.length >= SHARED_STEMS_LIMIT && share >= SHARED_SHARE_LIMIT) {
        return (
          `ролик повторяется: сцены ${i + 1} и ${j + 1} говорят одно и то же ` +
          `(общие слова: ${shared.slice(0, 4).join(", ")}). ` +
          "Во второй половине не должно быть пересказа первой"
        );
      }
    }
  }
  return undefined;
}
