import { MIX } from "./mix";

// Варианты появления и уход сцены. Смысл в разнообразии: подряд идущие сцены
// не должны двигаться одинаково, иначе ролик усыпляет. Набор перебирается по
// номеру сцены — детерминированно, чтобы рендер был повторяемым.

// Названия — по тому, что видно в кадре. spin и shuffle сняты с референса:
// карточка влетает крупной и повёрнутой и раскручивается на место; либо
// несколько карточек проходят внахлёст, как перебирают колоду.
export type EntryStyle =
  | "fade"
  | "overlay"
  | "slide"
  | "punch"
  | "swing"
  | "spin"
  | "shuffle"
  // Новая сцена приходит во весь кадр, размазанная зум-блюром, и садится в
  // рамку. В референсе это рабочая лошадка — три стыка из девяти.
  | "zoomIn"
  // Рваная шторка: новая картинка наползает на старую неровным краем, как
  // разлив чернил или надрыв бумаги.
  | "tornWipe";
// squeeze — схлопывание по горизонтали: карточка сжимается в вертикальную
// полоску и исчезает. В референсе из-за неё выходит маскот; маскота у нас
// пока нет, но само схлопывание работает и само по себе.
export type ExitStyle = "none" | "crumple" | "shrink" | "driftUp" | "squeeze";

// Переходы всего кадра из @remotion/transitions — другой класс движения, чем
// наши анимации карточки. Если у сцены задан library, то стык с СЛЕДУЮЩЕЙ
// сценой делает библиотека: карточка на этом стыке не мнётся и не уезжает
// (exit: "none"), а входящая сцена появляется без своего движения — иначе два
// перехода наложатся друг на друга и получится каша.
export type LibraryTransition = "wipe" | "flip" | "clockWipe" | "slide";

// Звуки на стыках бывают двух родов, и разница между ними не в тембре, а в
// том, КУДА их ставить.
//
// Импульс (щелчок, хлопок, снап, удар) — атака в единицы миллисекунд. Его
// ставят на сам стык: пик и есть начало файла. Такие звуки синтезируются,
// см. scripts/build-sfx.mjs.
//
// Вуш — наоборот, разгон в 80-320 мс и удар в конце разгона. Его надо ставить
// ЗАРАНЕЕ, чтобы пик пришёлся на склейку, а разгон отработал на уходящей
// сцене. Раньше здесь стояло «плавные наплывы на стыке читаются как
// размазанные» — и это было верно ровно потому, что звук ставился началом на
// стык: удар приходил через треть секунды после склейки и слышался как
// отдельное событие. Дело было в постановке, а не в самом классе звуков.
// Вуши записанные, лежат в assets/sfx, готовятся npm run sfx:import.
export type SfxName =
  | "click"
  | "clap"
  | "snap"
  | "impact"
  | "swoosh"
  | "swoosh-air"
  | "swoosh-deep"
  | "swoosh-wood"
  // Длинный кинематографичный вуш: разгон 0.83 с. Для стыка между сценами он
  // не годится — такой разгон залез бы в речь, — но ровно подходит выезду
  // брендовой концовки, перед которой речи уже нет.
  | "swoosh-long";

/**
 * На сколько миллисекунд раньше стыка начинать звук, чтобы его пик пришёлся
 * ровно на склейку. Числа не выдуманы: это измеренное положение пика в
 * готовом файле, его печатает npm run sfx:import, а test:timing сверяет
 * таблицу с файлами — чтобы правка звука не разошлась с постановкой.
 */
export const SFX_LEAD_MS: Record<SfxName, number> = {
  click: 0,
  clap: 0,
  snap: 0,
  impact: 0,
  swoosh: 110,
  "swoosh-air": 80,
  "swoosh-deep": 321,
  "swoosh-wood": 140,
  "swoosh-long": 827,
};

/**
 * Чем заменить звук, которого нет на диске.
 *
 * Сами вуши лежат в репозитории, так что в обычной сборке замена не нужна.
 * Она страховка: файл могут удалить, заменить своим или переименовать, а
 * ссылка на несуществующий файл роняет рендер на последнем кадре — когда уже
 * посчитаны и озвучка, и все картинки. Замена подобрана по весу: воздушному
 * вушу — щелчок, тяжёлому с низом — удар.
 */
const SFX_FALLBACK: Partial<Record<SfxName, SfxName>> = {
  swoosh: "clap",
  "swoosh-air": "click",
  "swoosh-deep": "impact",
  "swoosh-wood": "snap",
  "swoosh-long": "impact",
};

/**
 * Звук, который реально будем играть. `available` — имена файлов, найденных
 * в public/sfx на момент сборки данных; undefined означает «не проверяли»
 * (старые video-data.json), и тогда берём заведомо существующий синтез.
 */
export function resolveSfx(name: SfxName, available?: string[]): SfxName {
  const fallback = SFX_FALLBACK[name];
  if (!fallback) return name;
  return available?.includes(name) ? name : fallback;
}

export interface SceneMotion {
  entry: EntryStyle;
  exit: ExitStyle;
  // Звук на стыке сцен из public/sfx. Подбирается под характер перехода.
  sfx: SfxName;
  // Мягкий стык: карточка не двигается вовсе, одна картинка растворяется в
  // другой. В референсе такой стык длиннее резких и стоит там, где мысль
  // продолжается, а не меняется.
  soft?: boolean;
  // Усиленная подача: пружина мягче, подпись бьёт крупнее. Нужна хуку.
  emphasis?: boolean;
  // Переход из библиотеки на стыке со следующей сценой.
  library?: LibraryTransition;
}

// Пары подобраны так, чтобы уход предыдущей сцены сочетался с появлением
// следующей, а звук — с силой движения: смятие — удар, быстрый стык — щелчок
// или снап, зум-удар — хлопок.
// Звуки в цикле подобраны ещё и так, чтобы на соседних стыках не повторяться
// (первый стык — удар хука, поэтому у сцены 1 удара уже нет).
// Вуши расставлены не «где посвободнее», а по характеру движения: там, где
// кадр ПРОЛЕТАЕТ (разворот, наезд, шторка, перебор карточек), звук должен
// лететь вместе с ним. Там, где кадр бьётся или растворяется, вуш не к месту:
// на растворении он звучал бы движением, которого нет, а под смятие нужен
// удар, а не пролёт. Поэтому синтезированные импульсы из набора не вытеснены,
// а поделили цикл с записанными вушами примерно поровну.
const CYCLE: SceneMotion[] = [
  // Крупный разворот — самый тяжёлый вуш, с низом.
  { entry: "spin", exit: "squeeze", sfx: "swoosh-deep" },
  // Зум-блюр встречается в референсе чаще прочих, поэтому в цикле он дважды.
  // Наезд во весь кадр — обычный средний вуш.
  { entry: "zoomIn", exit: "none", sfx: "swoosh" },
  // Стык 2→3 — шторка: своего ухода у карточки нет, его делает переход.
  // Вуш светлый, без низа: шторка идёт краем, а не массой.
  { entry: "slide", exit: "none", sfx: "swoosh-air", library: "wipe" },
  // Мягкий стык: картинка меняется в неподвижной рамке. В референсе он один
  // на несколько резких — так же и здесь. Звук берём самый лёгкий из набора:
  // удар или вуш на растворении звучали бы громче, чем выглядит движение.
  { entry: "fade", exit: "none", sfx: "snap", soft: true },
  // Перебор карточек внахлёст — тот же средний вуш, что и на наезде: движение
  // по характеру такое же, а до соседнего его вхождения три стыка.
  { entry: "shuffle", exit: "crumple", sfx: "swoosh" },
  // Надрыв бумаги — сухой вуш с деревянным призвуком.
  { entry: "tornWipe", exit: "none", sfx: "swoosh-wood" },
  { entry: "zoomIn", exit: "squeeze", sfx: "impact" },
  { entry: "spin", exit: "driftUp", sfx: "clap" },
];

// Первая сцена — хук. Зритель решает за 1-2 секунды, поэтому кадр должен
// выстрелить, а не проявиться: наезд из мелкого масштаба с упругой пружиной,
// подпись сразу крупно, уход — смятием под глухой удар.
const HOOK_MOTION: SceneMotion = {
  entry: "punch",
  exit: "crumple",
  sfx: "impact",
  emphasis: true,
};

// Длина цикла: тесты сверяют по ней повторяемость, чтобы добавление вариантов
// не требовало правки проверок.
export const MOTION_CYCLE_LENGTH = CYCLE.length;

export function sceneMotion(index: number): SceneMotion {
  if (index === 0) return HOOK_MOTION;
  return CYCLE[index % CYCLE.length];
}

/**
 * Появление, которое само закрывает кадр целиком: зум-блюр приходит во весь
 * экран, рваная шторка вырезает сцену по краю. Такому входу не нужно ни
 * проявление поверх предыдущей сцены, ни её собственный уход — иначе в кадре
 * одновременно идут два разных движения и получается каша. Ровно тем же
 * свойством обладают переходы из библиотеки, поэтому обрабатываются они
 * одинаково.
 */
export function coversFrame(motion: SceneMotion): boolean {
  return motion.entry === "zoomIn" || motion.entry === "tornWipe";
}

/**
 * Сколько кадров длится стык перед следующей сценой. Мягкий идёт дольше
 * резкого — иначе он читается как обычная быстрая склейка и приём теряется.
 */
export function transitionFrames(motion: SceneMotion, fps: number): number {
  const seconds = motion.soft
    ? MIX.softTransitionSeconds
    : MIX.sharpTransitionSeconds;
  return Math.max(Math.round(seconds * fps), 1);
}
