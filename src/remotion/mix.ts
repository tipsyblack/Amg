// Уровни звуковых слоёв и длина стыка — в одном месте, потому что настраивают
// их всегда вместе и на слух.
//
// Порядок громкостей осмысленный: озвучка (1.0) главная, стык слышен поверх
// неё, звук хука чуть тише стыка (он длинный, и на полной громкости давил бы
// первую фразу), музыка — еле угадываемый фон. Проверяется в test:timing.
export const MIX = {
  // Фоновая музыка.
  //
  // Число выведено, а не подобрано на слух. Треки библиотеки приводятся к
  // −16 LUFS (prepareMusic.ts), голос в нашем миксе меряется около −14.8 LUFS
  // (замер присланного ролика: −14.6 LUFS на весь микс, и он почти целиком
  // речь). Подложка в говорящем ролике садится на 18 дБ ниже речи, значит ей
  // нужно −32.8 LUFS, то есть −16.8 дБ от −16 → множитель 0.145.
  //
  // Раньше здесь стояло 0.06, и это работало по случайности: Suno отдаёт треки
  // мастерингом около −8 LUFS, и −24 дБ от них давало те же −32. А трек,
  // положенный руками, мог быть и −20 LUFS — и тогда подложки не было слышно
  // вовсе. Теперь громкость трека известна заранее, и множитель означает
  // ровно то, что написано.
  music: 0.145,
  // Щелчок/хлопок/удар на стыке кадров. Выше 0.85 перебивает тихие голоса.
  sfx: 0.75,
  // Подъём с ударом на первом кадре ролика.
  hookSfx: 0.5,
  // Длительность стыка в СЕКУНДАХ, а не кадрах: fps теперь настраивается, а
  // на слух и на глаз переход измеряется временем. Числа сняты с референса —
  // резкие механики там укладываются в 0.28-0.32 с, а мягкий кроссфейд идёт
  // заметно дольше, 0.47 с. Раньше у нас все стыки были одной длины, и от
  // этого мягкий читался как резкий.
  //
  // Обе величины держим в пределах запаса тишины после реплики (0.4-0.5 с),
  // чтобы переход ложился на паузу, а не на речь.
  sharpTransitionSeconds: 0.3,
  softTransitionSeconds: 0.45,
  // Звук стыка играет на кадр раньше склейки — попадает в начало движения.
  sfxLeadFrames: 1,
  // Motion blur включаем только на кадрах перехода: он рендерит кадр
  // несколько раз, и на всём ролике умножил бы время рендера. 4 сэмплов
  // хватает, чтобы смазать быстрое движение; 10 (значение по умолчанию в
  // библиотеке) заметно дороже при почти том же результате.
  blurSamples: 4,
  blurShutterAngle: 180,
} as const;
