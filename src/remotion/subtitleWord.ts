// Выбор слова, которое показывается в кадре.
//
// В референсе субтитры сделаны предельно просто: в кадре ровно ОДНО слово,
// крупно, чёрным по белому, без плашки и без анимации — слово просто меняется
// на следующее в такт речи. Никаких «страниц» из нескольких слов с подсветкой
// текущего: их пришлось убрать, потому что это был другой приём.

export interface TimedWord {
  text: string;
  startMs: number;
  endMs: number;
}

/**
 * Слово в том виде, в котором оно показывается в кадре.
 *
 * Знаки препинания по краям убираются. Это снято с обоих референсов: в 14
 * подписях второго и во всех измеренных подписях первого нет ни точки, ни
 * запятой, ни вопросительного знака — «СКОЛЬКО», «ПОЛБЕДЫ», «СХАВАЕТ». У нас
 * же в кадр попадало «ДА?», «МОДЕЛЕЙ.», «ТОМ,» — потому что слово берётся из
 * реплики как есть.
 *
 * Убираются только КРАЯ: внутри знак может быть частью самого слова. В
 * референсе это видно на «0,5» — запятая там десятичная, и терять её нельзя;
 * то же с «как-то». Если после чистки не осталось ничего (слово было целиком
 * из знаков), показываем как было — пустой кадр хуже лишней точки.
 */
export function captionText(text: string): string {
  const trimmed = text
    .replace(/^[^\p{L}\p{N}]+/gu, "")
    .replace(/[^\p{L}\p{N}]+$/gu, "");
  return trimmed || text;
}

/**
 * Слово для текущего момента: последнее из начавшихся. Именно последнее, а не
 * «то, чей интервал содержит время» — между словами бывают паузы, и в них кадр
 * не должен оставаться без текста (в референсе слово висит до следующего).
 */
export function wordAt(
  words: TimedWord[],
  timeMs: number,
): TimedWord | undefined {
  // Перебор с конца: цель сборки ниже es2023, findLast недоступен.
  for (let i = words.length - 1; i >= 0; i--) {
    if (words[i].startMs <= timeMs) return words[i];
  }
  return undefined;
}
